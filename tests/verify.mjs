import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const storage = new Map();
const context = vm.createContext({ window: null, URL, AbortController, setTimeout, clearTimeout, Date, Map,
 localStorage: { getItem: key => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, value) }, fetch: null });
context.window = context;
for (const file of ['cache', 'api', 'images', 'categories']) vm.runInContext(readFileSync(`assets/js/${file}.js`, 'utf8'), context);
const { SW } = context;
const luke = { name: 'Luke Skywalker', url: 'https://swapi.dev/api/people/1/' };
const leia = { name: 'Leia Organa', url: 'https://swapi.dev/api/people/5/' };
let calls = [];
context.fetch = async url => {
 calls.push(url);
 return { ok: true, json: async () => url.includes('page=2') ? { count: 2, next: null, results: [leia] } : { count: 2, next: 'http://swapi.dev/api/people/?page=2', results: [luke] } };
};
const progress = [];
let result = await SW.api.load('people', (...args) => progress.push(args));
assert.equal(result.data.length, 2);
assert.equal(calls.length, 2);
assert.equal(calls[1], 'https://swapi.dev/api/people/?page=2');
assert.equal(progress[1][0], 2);
assert.equal(SW.cache.read('people').data.length, 2);
result = await SW.api.load('people');
assert.equal(result.source, 'cache');
assert.equal(calls.length, 2);
const old = { savedAt: Date.now() - SW.cache.maxAge - 1000, data: [luke] };
storage.set('swexplorer:v1:people', JSON.stringify(old));
context.fetch = async () => { throw new Error('offline'); };
result = await SW.api.load('people');
assert.equal(result.source, 'stale');
storage.clear();
await assert.rejects(SW.api.load('people'));
assert.equal(SW.cache.read('people'), null);
let page = 0;
context.fetch = async () => { if (page++) throw new Error('page failed'); return { ok: true, json: async () => ({ results: [luke], next: 'https://swapi.dev/api/people/?page=2' }) }; };
await assert.rejects(SW.api.load('people'));
assert.equal(SW.cache.read('people'), null, 'Não salva paginação incompleta');
context.fetch = async () => ({ ok: true, json: async () => ({ results: [luke], next: 'https://swapi.dev/api/people/' }) });
await assert.rejects(SW.api.all('people'), /Paginação/);
assert.throws(() => SW.api.safeUrl('https://example.com/api/people/'));
storage.set('swexplorer:v1:people', '{broken');
assert.equal(SW.cache.read('people'), null);
storage.set('swexplorer:v1:people', JSON.stringify({ savedAt: Date.now(), data: [null] }));
assert.equal(SW.cache.read('people'), null);
context.localStorage.setItem = () => { throw new Error('quota'); };
assert.equal(SW.cache.write('people', [luke]), false);
context.fetch = async () => ({ ok: true, json: async () => ({ results: [luke], next: null }) });
result = await SW.api.load('people');
assert.equal(result.source, 'memory');
let relations = 0;
context.fetch = async () => { relations++; return { ok: true, json: async () => ({ name: 'Tatooine' }) }; };
assert.equal(await SW.api.relation('http://swapi.dev/api/planets/1/'), 'Tatooine');
assert.equal(await SW.api.relation('https://swapi.dev/api/planets/1/'), 'Tatooine');
assert.equal(relations, 1);
assert.equal(SW.images.id(luke.url), '1');
assert.equal(SW.images.get('people', luke.url), 'assets/images/fallback.svg');
assert.equal(SW.format('unknown', 'mass'), 'Não informado');
console.log('PASS: paginação, HTTPS, cache válido/vencido/corrompido, erro, paginação parcial/cíclica, armazenamento bloqueado, relações e imagens.');
